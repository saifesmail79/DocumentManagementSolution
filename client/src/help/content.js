/**
 * The topic for a path, used when the screen has not declared one of its own.
 *
 * Administration overrides it through `useHelpTopic`, because nine tabs behind
 * one route cannot share one description. My space does not: its four tabs are
 * close enough in purpose that one topic listing them reads better than four.
 * Everything else is covered here, which is what stops the button ever opening
 * onto nothing.
 */
export function topicForPath(pathname) {
  const match = ROUTE_TOPICS.find(([prefix]) => pathname.startsWith(prefix));
  return match ? match[1] : 'folders';
}

