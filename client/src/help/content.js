/**
 * The help text, kept apart from the components that show it.
 *
 * ─── Why a registry rather than props on each page ──────────────────────────
 *
 * Help that lives inside the page it describes is help that gets missed: a new
 * page ships without it and nothing says so. Here every screen is one entry in
 * one object, so what is documented and what is not is a list you can read, and
 * `MISSING_TOPICS` below turns a gap into something a test can fail on.
 *
 * ─── What belongs in an entry ───────────────────────────────────────────────
 *
 * What the screen is for, what the controls on it do, and — the part users
 * actually need — the behaviour that is invisible until it surprises them:
 * indexing that lags an upload, a deletion that is reversible only for a while,
 * a permission that hides content but not its name. Anything already obvious
 * from a label on screen is left out; repeating it just buries the rest.
 *
 * Written in Arabic, like the interface. `title` matches the heading on screen
 * so the panel is visibly about the thing behind it.
 */

